/* =========================================
   AUTO VIDEO GENERATION
========================================= */

async function generateAutoVideo(contentId, slot) {

    const token =
        localStorage.getItem("token");

    if (!token) {
        alert("خاصك تسجل الدخول أولاً.");
        return;
    }

    if (!contentId) {
        alert("معرف المحتوى غير موجود.");
        return;
    }

    if (!["morning", "evening"].includes(slot)) {
        alert("نوع المنشور غير صحيح.");
        return;
    }

    const buttons =
        document.querySelectorAll(
            `[data-auto-video-slot="${slot}"]`
        );

    buttons.forEach(button => {
        button.disabled = true;
        button.textContent = "🎬 جاري إنشاء الفيديو...";
    });

    try {

        const response =
            await fetch(
                "/auto-content/video",
                {
                    method: "POST",

                    headers: {
                        "Content-Type": "application/json",
                        "Authorization":
                            "Bearer " + token
                    },

                    body: JSON.stringify({
                        contentId,
                        slot
                    })
                }
            );

        const data =
            await response.json();

        if (!response.ok || !data.success) {
            throw new Error(
                data.message ||
                "تعذر إنشاء الفيديو."
            );
        }

        if (
            autoGeneratedContent &&
            autoGeneratedContent[slot]
        ) {
            autoGeneratedContent[slot].video =
                data.video;
        }

        renderAutoContent();

    } catch (error) {

        console.error(
            "AUTO VIDEO FRONTEND ERROR:",
            error
        );

        alert(
            "❌ " +
            (error.message ||
                "تعذر إنشاء الفيديو.")
        );

        buttons.forEach(button => {
            button.disabled = false;
            button.textContent = "🎬 إنشاء الفيديو";
        });
    }
}


/* =========================================
   PUBLISH AUTO VIDEO TO YOUTUBE
========================================= */

async function publishAutoVideoToYouTube(contentId, slot) {

    const token =
        localStorage.getItem("token");

    if (!token) {
        alert("خاصك تسجل الدخول أولاً.");
        return;
    }

    if (!contentId) {
        alert("معرف المحتوى غير موجود.");
        return;
    }

    if (!["morning", "evening"].includes(slot)) {
        alert("نوع المنشور غير صحيح.");
        return;
    }

    const post =
        autoGeneratedContent?.[slot];

    if (!post || !post.video) {
        alert("خاصك تنشئ الفيديو أولاً.");
        return;
    }

    if (post.youtubeUrl) {
        alert("هذا الفيديو منشور مسبقاً على YouTube.");
        return;
    }

    const button =
        document.querySelector(
            `[data-auto-youtube-slot="${slot}"]`
        );

    if (button) {
        button.disabled = true;
        button.textContent =
            "📤 جاري النشر على YouTube...";
    }

    const hashtags =
        Array.isArray(post.hashtags)
            ? post.hashtags.join(" ")
            : "";

    const description =
        [
            post.caption || "",
            "",
            hashtags
        ]
        .filter(Boolean)
        .join("\n");

    try {

        const response =
            await fetch(
                "/youtube/upload-generated",
                {
                    method: "POST",

                    headers: {
                        "Content-Type":
                            "application/json",

                        "Authorization":
                            "Bearer " + token
                    },

                    body: JSON.stringify({

                        contentId,

                        slot,

                        videoPath:
                            post.video,

                        title:
                            post.title || "UltraAI",

                        description,

                        privacyStatus:
                            "public"
                    })
                }
            );

        const data =
            await response.json();

        if (!response.ok || !data.success) {
            throw new Error(
                data.message ||
                "تعذر نشر الفيديو على YouTube."
            );
        }

        post.youtubeUrl =
            data.url || "";

        post.youtubeVideoId =
            data.videoId || "";

        renderAutoContent();

        alert(
            "✅ تم نشر الفيديو على YouTube بنجاح!"
        );

    } catch (error) {

        console.error(
            "AUTO YOUTUBE PUBLISH ERROR:",
            error
        );

        alert(
            "❌ " +
            (
                error.message ||
                "تعذر نشر الفيديو."
            )
        );

        if (button) {
            button.disabled = false;
            button.textContent =
                "📤 نشر على YouTube";
        }
    }
}

window.publishAutoVideoToYouTube =
    publishAutoVideoToYouTube;

window.generateAutoVideo =
    generateAutoVideo;

