async function copyAutoPost(post) {

    if (!post) return;

    const hashtags =
        Array.isArray(post.hashtags)
            ? post.hashtags.join(" ")
            : "";

    const text = `
${post.title || ""}

HOOK:
${post.hook || ""}

SCRIPT:
${post.script || ""}

CAPTION:
${post.caption || ""}

${hashtags}
`.trim();

    try {

        await navigator.clipboard.writeText(text);

        alert("تم نسخ المحتوى ✅");

    } catch (error) {

        console.error(
            "Auto copy error:",
            error
        );

        alert("تعذر نسخ المحتوى.");
    }
}


function escapeAutoContent(text) {

    return String(text || "")
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}

        
function parseJwtPayload(token) {

    try {

        const parts = String(token).split(".");

        if (parts.length !== 3) {
            return null;
        }

        const base64 =
            parts[1]
                .replace(/-/g, "+")
                .replace(/_/g, "/");

        return JSON.parse(
            decodeURIComponent(
                atob(base64)
                    .split("")
                    .map(
                        c =>
                            "%" +
                            (
                                "00" +
                                c.charCodeAt(0).toString(16)
                            ).slice(-2)
                    )
                    .join("")
            )
        );

    } catch (error) {

        console.error(
            "JWT payload error:",
            error
        );

        return null;
    }
}

