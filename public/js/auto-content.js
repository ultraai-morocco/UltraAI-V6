async function loadTikTokStatus() {

    const token = localStorage.getItem("token");

    const text =
        document.getElementById("tiktokConnectionText");

    const button =
        document.getElementById("tiktokConnectBtn");

    if (!text || !button) return;

    if (!token) {
        text.textContent =
            "خاصك تسجل الدخول أولاً.";

        button.textContent =
            "🎵 ربط TikTok";

        button.disabled = false;

        return;
    }

    try {

        const response =
            await fetch(
                "/tiktok/status?t=" + Date.now(),
                {
                    method: "GET",
                    cache: "no-store",
                    headers: {
                        "Authorization":
                            "Bearer " + token
                    }
                }
            );

        const data =
            await response.json();

        console.log(
            "🎵 TikTok status:",
            data
        );

        if (
            data.success &&
            data.connected === true
        ) {

            text.textContent =
                "حساب TikTok مربوط بنجاح ✅";

            /*
             * نخلي الزر قابل للضغط
             * لإعادة Authorization.
             */
            button.textContent =
                "🔄 إعادة ربط TikTok";

            button.disabled = false;

        } else {

            text.textContent =
                "ربط حساب TikTok باش تقدر تنشر المحتوى مباشرة.";

            button.textContent =
                "🎵 ربط TikTok";

            button.disabled = false;
        }

    } catch (error) {

        console.error(
            "TikTok status error:",
            error
        );

        text.textContent =
            "تعذر التحقق من حالة TikTok.";

        button.textContent =
            "🎵 ربط TikTok";

        button.disabled = false;
    }
}

window.loadTikTokStatus = loadTikTokStatus;

