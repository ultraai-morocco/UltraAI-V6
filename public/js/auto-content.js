let autoGeneratedContent = null;

async function generateAutoContent() {

    const niche =
        document.getElementById("autoNiche")?.value.trim() || "";

    const audience =
        document.getElementById("autoAudience")?.value.trim() || "";

    const language =
        document.getElementById("autoLanguage")?.value || "ar";

    const result =
        document.getElementById("autoContentResult");

    if (!result) return;

    if (!niche) {
        result.style.display = "block";
        result.innerHTML = `
            <div class="auto-content-error">
                ⚠️ دخل النيش أولاً.
            </div>
        `;
        return;
    }

    result.style.display = "block";

    result.innerHTML = `
        <div class="auto-content-loading">
            <div class="auto-loading-icon">✨</div>
            <strong>جاري صناعة المحتوى...</strong>
            <span>
                UltraAI يحضر لك فكرة صباحية وفكرة مسائية
            </span>
        </div>
    `;

    try {

        const token =
            localStorage.getItem("token");

        if (!token) {
            throw new Error(
                "خاصك تسجل الدخول أولاً."
            );
        }

        const response =
            await fetch("/auto-content/generate", {
                method: "POST",

                headers: {
                    "Content-Type": "application/json",
                    "Authorization":
                        "Bearer " + token
                },

                body: JSON.stringify({
                    niche,
                    audience,
                    language
                })
            });

        const data =
            await response.json();

        if (!response.ok) {
            throw new Error(
                data.message ||
                data.error ||
                "تعذر توليد المحتوى."
            );
        }

        autoGeneratedContent =
            data.content || null;

        renderAutoContent();

    } catch (error) {

        console.error(
            "Auto Content error:",
            error
        );

        result.innerHTML = `
            <div class="auto-content-error">
                ❌ ${escapeAutoContent(error.message)}
                <button onclick="generateAutoContent()">
                    حاول مرة أخرى
                </button>
            </div>
        `;
    }
}


function renderAutoContent() {

    const result =
        document.getElementById("autoContentResult");

    if (!result || !autoGeneratedContent) {
        return;
    }

    const morning =
        autoGeneratedContent.morning || {};

    const evening =
        autoGeneratedContent.evening || {};

    result.innerHTML = `

        <div class="auto-content-results-header">

            <div>
                <strong>🎬 المحتوى الجاهز</strong>
                <span>
                    ${escapeAutoContent(
                        autoGeneratedContent.niche
                    )}
                </span>
            </div>

            <button
                type="button"
                onclick="generateAutoContent()"
            >
                🔄 جديد
            </button>

        </div>


        <div class="auto-content-grid">


            <article class="auto-post-card">

                <div class="auto-post-header">
                    <span>🌅</span>
                    <strong>منشور الصباح</strong>
                </div>

                ${renderAutoPost(morning, "morning")}

            </article>


            <article class="auto-post-card">

                <div class="auto-post-header">
                    <span>🌙</span>
                    <strong>منشور المساء</strong>
                </div>

                ${renderAutoPost(evening, "evening")}

            </article>


        </div>
    `;
}


